"""
fact_generator.py -- Immutable Fact Ledger Generator (Dev 1 * Phase 3)

Responsibilities
----------------
* Assemble outputs from Phase 1 (SandboxEnv), Phase 2 (BaselineResult),
  and Phase 3 (SwappedWorktree, VerdictReport) into a STRICT JSON Fact Ledger.
* Contains exactly the fields required by the architecture contract:
    - ``run_id``: Unique run identifier
    - ``base_sha``: 40-character commit SHA of target repository
    - ``py_version``: Validated Python version (e.g. "3.12.10")
    - ``candidate``: Candidate package replacement tested
    - ``patch_sha``: SHA256 digest of AI-generated patch (or None)
    - ``baseline_res``: Structured summary of double-baseline runs
    - ``swapped_res``: Structured summary of swapped worktree test run
    - ``flaky``: Array of flaky node IDs mathematically excluded
    - ``verdict``: Final decision ("PASS", "FAIL", or "INCONCLUSIVE")
    - ``junit_path``: Path to JUnit XML generated by the swapped run
* Calculate cryptographic integrity hash (``ledger_sha256``) over canonical JSON
  for tamper-evident audit logging.
* Persist ledger to disk as deterministic JSON.

Zero external dependencies -- stdlib only (hashlib, json, uuid, datetime,
dataclasses, pathlib).
"""

from __future__ import annotations

import datetime
import hashlib
import json
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Final

from sandbox.ast_census import CensusReport
from sandbox.baseline import BaselineResult
from sandbox.env_manager import SandboxEnv
from sandbox.swapper import SwappedWorktree
from sandbox.verdict import VerdictReport



# ---------------------------------------------------------------------------
# Data class
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class FactLedger:
    """
    Strict, immutable audit ledger containing all facts collected across
    Phases 1, 2, and 3.

    Fields
    ------
    run_id:
        Unique UUID / identifier for this execution run.
    base_sha:
        Full 40-character git commit SHA of the base repository.
    py_version:
        CPython interpreter version triple string (e.g. ``"3.12.10"``).
    candidate:
        Candidate package specifier tested.
    patch_sha:
        SHA256 hex digest of the applied AI patch, or None if unpatched.
    baseline_res:
        Summary metrics from the double-baseline phase.
    swapped_res:
        Summary metrics from the swapped worktree test run.
    flaky:
        Sorted array of flaky test nodeids excluded from final verdict.
    verdict:
        Final evaluation verdict (``"PASS"``, ``"FAIL"``, or ``"INCONCLUSIVE"``).
    junit_path:
        Path to the JUnit XML file produced during the swapped test run.
    timestamp_utc:
        ISO 8601 UTC timestamp of ledger generation.
    ledger_sha256:
        SHA256 hash of canonical JSON content (excluding the hash itself),
        providing cryptographic proof against post-hoc tampering.
    """

    run_id: str
    base_sha: str
    py_version: str
    candidate: str
    patch_sha: str | None
    baseline_res: dict[str, object]
    swapped_res: dict[str, object]
    flaky: list[str]
    verdict: str
    junit_path: str
    timestamp_utc: str
    usage_locations: dict[str, object] | None = None
    ledger_sha256: str = field(default="")

    def to_dict(self, *, include_hash: bool = True) -> dict[str, object]:
        """Convert ledger to a serializable dictionary."""
        d: dict[str, object] = {
            "run_id": self.run_id,
            "base_sha": self.base_sha,
            "py_version": self.py_version,
            "candidate": self.candidate,
            "patch_sha": self.patch_sha,
            "baseline_res": self.baseline_res,
            "swapped_res": self.swapped_res,
            "flaky": self.flaky,
            "verdict": self.verdict,
            "junit_path": self.junit_path,
            "timestamp_utc": self.timestamp_utc,
            "usage_locations": self.usage_locations,
        }
        if include_hash:
            d["ledger_sha256"] = self.ledger_sha256
        return d


    def to_canonical_json(self) -> str:
        """Produce canonical, deterministic JSON string of core fields."""
        d = self.to_dict(include_hash=False)
        return json.dumps(d, sort_keys=True, separators=(",", ":"), default=str)

    def to_json(self, indent: int = 2) -> str:
        """Serialize full ledger to formatted JSON string."""
        return json.dumps(self.to_dict(include_hash=True), indent=indent, default=str)

    def verify_integrity(self) -> bool:
        """
        Verify that ``ledger_sha256`` matches the SHA256 of canonical fields.

        Returns
        -------
        bool
            True if ledger has not been tampered with.
        """
        expected = hashlib.sha256(self.to_canonical_json().encode("utf-8")).hexdigest()
        return self.ledger_sha256 == expected

    def save(self, output_path: Path | str) -> Path:
        """
        Save the ledger to a JSON file.

        Parameters
        ----------
        output_path:
            Target file path.

        Returns
        -------
        Path
            Resolved path of the written file.
        """
        dest = Path(output_path).resolve()
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(self.to_json(indent=2), encoding="utf-8")
        return dest


# ---------------------------------------------------------------------------
# Factory functions
# ---------------------------------------------------------------------------


def build_fact_ledger(
    env: SandboxEnv,
    swapped: SwappedWorktree,
    baseline: BaselineResult,
    verdict_report: VerdictReport,
    *,
    census_report: CensusReport | None = None,
    run_id: str | None = None,
    junit_path: Path | str | None = None,
) -> FactLedger:
    """
    Construct a validated, tamper-hashed ``FactLedger``.

    Parameters
    ----------
    env:
        Phase 1 SandboxEnv descriptor.
    swapped:
        Phase 3 SwappedWorktree descriptor.
    baseline:
        Phase 2 BaselineResult descriptor.
    verdict_report:
        Phase 3 VerdictReport descriptor.
    census_report:
        Optional Phase 1 CensusReport descriptor containing AST usage locations.
    run_id:
        Optional unique run identifier. If None, generates UUIDv4.
    junit_path:
        Optional path to JUnit XML. If None, derived from swapped_run or worktree.

    Returns
    -------
    FactLedger
        Immutable, cryptographically hashed Fact Ledger.
    """
    resolved_run_id = run_id or f"run_{uuid.uuid4().hex}"
    timestamp = datetime.datetime.now(datetime.timezone.utc).isoformat()
    usage_locations = census_report.to_dict() if census_report is not None else None

    # Resolve JUnit XML path
    if junit_path is not None:
        xml_path_str = str(Path(junit_path).resolve())
    elif verdict_report.swapped_run and verdict_report.swapped_run.xml_path:
        xml_path_str = str(verdict_report.swapped_run.xml_path.resolve())
    else:
        xml_path_str = str(swapped.worktree_dir / "junit.xml")

    # Construct baseline_res dict
    baseline_res: dict[str, object] = {
        "is_clean": baseline.is_baseline_clean,
        "stable_pass_count": len(baseline.stable_pass_nodeids),
        "stable_fail_count": len(baseline.stable_fail_nodeids),
        "flaky_count": baseline.flaky_count,
        "run1_exit_code": baseline.run1.exit_code,
        "run2_exit_code": baseline.run2.exit_code,
    }

    # Construct swapped_res dict
    swapped_run = verdict_report.swapped_run
    swapped_res: dict[str, object] = {
        "exit_code": swapped_run.exit_code if swapped_run else -1,
        "passed_count": verdict_report.swapped_passed_count,
        "failed_count": verdict_report.swapped_failed_count,
        "error_count": verdict_report.swapped_error_count,
        "skipped_count": verdict_report.swapped_skipped_count,
        "regressed_nodeids": verdict_report.regressed_nodeids,
        "fixed_nodeids": verdict_report.fixed_nodeids,
    }

    flaky_list = sorted(list(baseline.flaky_nodeids))

    # Pre-build without hash to compute canonical hash
    canonical_payload = json.dumps(
        {
            "run_id": resolved_run_id,
            "base_sha": swapped.base_sha,
            "py_version": str(env.python_version),
            "candidate": swapped.candidate_package,
            "patch_sha": swapped.patch_sha,
            "baseline_res": baseline_res,
            "swapped_res": swapped_res,
            "flaky": flaky_list,
            "verdict": verdict_report.verdict.value,
            "junit_path": xml_path_str,
            "timestamp_utc": timestamp,
            "usage_locations": usage_locations,
        },
        sort_keys=True,
        separators=(",", ":"),
        default=str,
    )

    ledger_hash = hashlib.sha256(canonical_payload.encode("utf-8")).hexdigest()

    return FactLedger(
        run_id=resolved_run_id,
        base_sha=swapped.base_sha,
        py_version=str(env.python_version),
        candidate=swapped.candidate_package,
        patch_sha=swapped.patch_sha,
        baseline_res=baseline_res,
        swapped_res=swapped_res,
        flaky=flaky_list,
        verdict=verdict_report.verdict.value,
        junit_path=xml_path_str,
        timestamp_utc=timestamp,
        usage_locations=usage_locations,
        ledger_sha256=ledger_hash,
    )

